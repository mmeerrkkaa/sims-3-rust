#[derive(Default)]
struct Counter {
    calls: AtomicU64,
    nanos: AtomicU64,
    max_nanos: AtomicU64,
}

pub struct Snapshot {
    pub section: Section,
    pub calls: u64,
    pub nanos: u64,
    pub max_nanos: u64,
}

impl Counter {
    fn record(&self, nanos: u64) {
        self.nanos.fetch_add(nanos, Ordering::Relaxed);
        self.max_nanos.fetch_max(nanos, Ordering::Relaxed);
        self.calls.fetch_add(1, Ordering::Relaxed);
    }

    fn take(&self, section: Section) -> Snapshot {
        Snapshot {
            section,
            calls: self.calls.swap(0, Ordering::Relaxed),
            nanos: self.nanos.swap(0, Ordering::Relaxed),
            max_nanos: self.max_nanos.swap(0, Ordering::Relaxed),
        }
    }
}

static ENABLED: AtomicBool = AtomicBool::new(false);
static COUNTERS: [Counter; 144] = [const {
    Counter {
        calls: AtomicU64::new(0),
        nanos: AtomicU64::new(0),
        max_nanos: AtomicU64::new(0),
    }
}; 144];

pub fn enable() {
    ENABLED.store(true, Ordering::Relaxed);
}

#[must_use]
pub struct Guard {
    section: Section,
    start: Instant,
}

#[inline]
pub fn measure(section: Section) -> Option<Guard> {
    ENABLED.load(Ordering::Relaxed).then(|| Guard {
        section,
        start: Instant::now(),
    })
}

impl Drop for Guard {
    fn drop(&mut self) {
        COUNTERS[self.section as usize]
            .record(self.start.elapsed().as_nanos().min(u64::MAX as u128) as u64);
    }
}

/// Drain after Update has joined its workers. Nested scopes are inclusive.
pub fn drain() -> Vec<Snapshot> {
    ALL.into_iter()
        .map(|s| COUNTERS[s as usize].take(s))
        .filter(|s| s.calls > 0)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Arc;

    #[test]
    fn concurrent_calls_are_preserved_and_windows_reset() {
        let counter = Arc::new(Counter::default());
        std::thread::scope(|scope| {
            for n in 1..=8 {
                let counter = counter.clone();
                scope.spawn(move || {
                    for _ in 0..1000 {
                        counter.record(n);
                    }
                });
            }
        });
        let sample = counter.take(Section::Autonomy);
        assert_eq!(sample.calls, 8000);
        assert_eq!(sample.nanos, 36000);
        assert_eq!(sample.max_nanos, 8);
        assert_eq!(counter.take(Section::Autonomy).calls, 0);
        counter.record(3);
        let next = counter.take(Section::Autonomy);
        assert_eq!((next.calls, next.nanos, next.max_nanos), (1, 3, 3));
    }
}
